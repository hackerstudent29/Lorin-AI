"""
MSAJCE RAG – LLM-as-a-Judge Evaluation Pipeline
Scores the live chatbot on:
  • Faithfulness   – Is the answer grounded in retrieved sources (no hallucination)?
  • Answer Relevancy – Does the answer directly address the question?
  • Correctness    – Does the answer match the expected ground-truth answer?

Uses NVIDIA NIM (meta/llama-3.1-70b-instruct) as the judge LLM.
Does NOT depend on the broken `ragas` library.

Usage:
    python eval/ragas_eval.py [--dataset FILE] [--api-url URL] [--sample N]
"""

import os, sys, json, time, argparse, datetime
from pathlib import Path
from dotenv import load_dotenv

load_dotenv()

# ── Judge Prompts ─────────────────────────────────────────────────────────────

FAITHFULNESS_PROMPT = """You are an expert evaluator. Given a QUESTION, the CONTEXT (retrieved source chunks), and the ANSWER generated by a chatbot, score how faithful the ANSWER is to the CONTEXT.

Faithfulness measures whether every claim in the ANSWER can be traced back to the CONTEXT. If the answer contains information NOT present in the CONTEXT, it is unfaithful (hallucinated).

Scoring:
- 1.0 = Every claim in the answer is fully supported by the context.
- 0.75 = Most claims are supported, with only minor unsupported details.
- 0.5 = Some claims are supported but significant information is added.
- 0.25 = Most claims are unsupported or fabricated.
- 0.0 = The answer is entirely hallucinated with no basis in the context.

QUESTION: {question}

CONTEXT:
{context}

ANSWER: {answer}

Respond with ONLY a JSON object: {{"score": <float>, "reason": "<brief explanation>"}}"""

RELEVANCY_PROMPT = """You are an expert evaluator. Given a QUESTION and an ANSWER generated by a chatbot, score how relevant and directly the ANSWER addresses the QUESTION.

Relevancy measures whether the answer is on-topic and directly responds to what was asked. Off-topic, vague, or overly generic answers score low.

Scoring:
- 1.0 = The answer directly and completely addresses the question.
- 0.75 = The answer mostly addresses the question with minor tangents.
- 0.5 = The answer partially addresses the question but is vague or includes much irrelevant info.
- 0.25 = The answer barely touches on the question.
- 0.0 = The answer is completely irrelevant to the question.

QUESTION: {question}

ANSWER: {answer}

Respond with ONLY a JSON object: {{"score": <float>, "reason": "<brief explanation>"}}"""

CORRECTNESS_PROMPT = """You are an expert evaluator. Given a QUESTION, the EXPECTED ANSWER (ground truth), and the GENERATED ANSWER from a chatbot, score how correct the GENERATED ANSWER is compared to the EXPECTED ANSWER.

Correctness measures factual accuracy relative to the ground truth. The generated answer does not need to be word-for-word identical, but it should convey the same key facts.

Scoring:
- 1.0 = The generated answer captures all key facts from the expected answer.
- 0.75 = The generated answer captures most key facts with minor omissions.
- 0.5 = The generated answer captures some key facts but misses important ones.
- 0.25 = The generated answer has very few correct facts.
- 0.0 = The generated answer is factually wrong or completely misses the point.

QUESTION: {question}

EXPECTED ANSWER: {expected}

GENERATED ANSWER: {generated}

Respond with ONLY a JSON object: {{"score": <float>, "reason": "<brief explanation>"}}"""


# ── NVIDIA NIM Judge ──────────────────────────────────────────────────────────

def call_judge(prompt: str, api_key: str) -> dict:
    """Call NVIDIA NIM judge LLM and parse the JSON score response."""
    import openai

    client = openai.OpenAI(
        api_key=api_key,
        base_url="https://integrate.api.nvidia.com/v1"
    )

    for attempt in range(3):
        try:
            resp = client.chat.completions.create(
                model="meta/llama-3.1-70b-instruct",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.1,
                max_tokens=300,
            )
            text = resp.choices[0].message.content.strip()
            # Extract JSON from response (handle markdown fences)
            if "```" in text:
                text = text.split("```")[1]
                if text.startswith("json"):
                    text = text[4:]
            # Find JSON object in text
            start = text.find("{")
            end = text.rfind("}") + 1
            if start >= 0 and end > start:
                return json.loads(text[start:end])
            return {"score": 0.0, "reason": f"Could not parse judge response: {text[:100]}"}
        except Exception as e:
            if attempt < 2:
                time.sleep(2 ** attempt)
                continue
            return {"score": 0.0, "reason": f"Judge call failed: {e}"}


# ── Main Evaluation ──────────────────────────────────────────────────────────

def run_eval(dataset_path: str, api_url: str, sample_size: int | None = None):
    NVIDIA_API_KEY = os.getenv("NVIDIA_API_KEY")
    if not NVIDIA_API_KEY:
        print("[ERROR] NVIDIA_API_KEY not found in environment.")
        sys.exit(1)

    # Load dataset
    p = Path(dataset_path)
    if not p.exists():
        print(f"[ERROR] Dataset {dataset_path} not found.")
        sys.exit(1)

    with open(p, "r", encoding="utf-8") as f:
        raw_data = json.load(f)

    if sample_size and sample_size < len(raw_data):
        import random
        random.seed(42)
        raw_data = random.sample(raw_data, sample_size)

    print(f"\n{'='*60}")
    print(f"  MSAJCE RAG – LLM-as-a-Judge Evaluation")
    print(f"  Dataset:    {len(raw_data)} questions")
    print(f"  API:        {api_url}")
    print(f"  Judge LLM:  meta/llama-3.1-70b-instruct (NVIDIA NIM)")
    print(f"{'='*60}\n")

    import requests
    results = []
    errors = 0

    for i, item in enumerate(raw_data, 1):
        q = item["question"]
        gt = item["expected_answer"]
        category = item.get("category", "")
        print(f"  [{i:2d}/{len(raw_data)}] {q[:65]}...")

        try:
            # Step 1: Get chatbot answer
            t0 = time.monotonic()
            resp = requests.post(
                f"{api_url}/api/chat",
                json={"message": q, "session_id": "00000000-eval-0000-0000-000000000001", "bypass_cache": True},
                timeout=60
            )
            latency_ms = int((time.monotonic() - t0) * 1000)
            resp.raise_for_status()
            data = resp.json()

            answer = data.get("answer", "")
            citations = data.get("citations", [])
            # Build context string from citations for faithfulness eval
            context_parts = []
            for c in citations:
                src = c.get("source", "unknown")
                section = c.get("section", "")
                text = c.get("text", c.get("snippet", ""))
                if text:
                    context_parts.append(f"[{src} - {section}]: {text}")
                else:
                    context_parts.append(f"[{src} - {section}]")
            context_str = "\n".join(context_parts) if context_parts else "No context retrieved."

            # Step 2: Judge – Faithfulness
            faith_result = call_judge(
                FAITHFULNESS_PROMPT.format(question=q, context=context_str, answer=answer),
                NVIDIA_API_KEY
            )

            # Step 3: Judge – Relevancy
            rel_result = call_judge(
                RELEVANCY_PROMPT.format(question=q, answer=answer),
                NVIDIA_API_KEY
            )

            # Step 4: Judge – Correctness
            corr_result = call_judge(
                CORRECTNESS_PROMPT.format(question=q, expected=gt, generated=answer),
                NVIDIA_API_KEY
            )

            result = {
                "question": q,
                "expected_answer": gt,
                "generated_answer": answer,
                "category": category,
                "num_citations": len(citations),
                "latency_ms": latency_ms,
                "faithfulness": faith_result.get("score", 0.0),
                "faithfulness_reason": faith_result.get("reason", ""),
                "relevancy": rel_result.get("score", 0.0),
                "relevancy_reason": rel_result.get("reason", ""),
                "correctness": corr_result.get("score", 0.0),
                "correctness_reason": corr_result.get("reason", ""),
            }
            results.append(result)

            print(f"           Faith={result['faithfulness']:.2f}  "
                  f"Rel={result['relevancy']:.2f}  "
                  f"Corr={result['correctness']:.2f}  "
                  f"{latency_ms}ms")

        except Exception as e:
            print(f"           [ERROR] {e}")
            errors += 1
            results.append({
                "question": q, "error": str(e),
                "faithfulness": 0.0, "relevancy": 0.0, "correctness": 0.0,
                "latency_ms": 0
            })

    # ── Aggregate ─────────────────────────────────────────────────────────
    valid = [r for r in results if "error" not in r]
    n = max(len(valid), 1)

    agg = {
        "mean_faithfulness":  round(sum(r["faithfulness"] for r in valid) / n, 4),
        "mean_relevancy":     round(sum(r["relevancy"] for r in valid) / n, 4),
        "mean_correctness":   round(sum(r["correctness"] for r in valid) / n, 4),
        "mean_latency_ms":    int(sum(r["latency_ms"] for r in valid) / n),
        "total_questions":    len(raw_data),
        "successful":         len(valid),
        "errors":             errors,
    }

    # Per-category breakdown
    categories = {}
    for r in valid:
        cat = r.get("category", "Other")
        if cat not in categories:
            categories[cat] = {"faithfulness": [], "relevancy": [], "correctness": []}
        categories[cat]["faithfulness"].append(r["faithfulness"])
        categories[cat]["relevancy"].append(r["relevancy"])
        categories[cat]["correctness"].append(r["correctness"])

    cat_summary = {}
    for cat, scores in categories.items():
        cn = len(scores["faithfulness"])
        cat_summary[cat] = {
            "count": cn,
            "mean_faithfulness": round(sum(scores["faithfulness"]) / cn, 4),
            "mean_relevancy":    round(sum(scores["relevancy"]) / cn, 4),
            "mean_correctness":  round(sum(scores["correctness"]) / cn, 4),
        }

    # ── Print Summary ─────────────────────────────────────────────────────
    print(f"\n{'='*60}")
    print(f"  LLM-as-a-Judge Results ({len(valid)} questions)")
    print(f"{'='*60}")
    print(f"  Faithfulness:    {agg['mean_faithfulness']*100:.1f}%")
    print(f"  Relevancy:       {agg['mean_relevancy']*100:.1f}%")
    print(f"  Correctness:     {agg['mean_correctness']*100:.1f}%")
    print(f"  Mean Latency:    {agg['mean_latency_ms']} ms")
    if errors:
        print(f"  Errors:          {errors}")
    print(f"\n  Per-Category Breakdown:")
    for cat, s in sorted(cat_summary.items()):
        print(f"    {cat:35s}  F={s['mean_faithfulness']:.2f}  R={s['mean_relevancy']:.2f}  C={s['mean_correctness']:.2f}  (n={s['count']})")
    print(f"{'='*60}\n")

    # ── Save Results ──────────────────────────────────────────────────────
    timestamp = datetime.datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    output_path = Path(f"eval/ragas_results_{timestamp}.json")
    output_path.parent.mkdir(exist_ok=True)

    output_data = {
        "timestamp":    datetime.datetime.utcnow().isoformat() + "Z",
        "judge_model":  "meta/llama-3.1-70b-instruct",
        "aggregate":    agg,
        "per_category": cat_summary,
        "questions":    results,
    }
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output_data, f, indent=2, ensure_ascii=False)
    print(f"  Results saved to: {output_path}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="MSAJCE RAG – LLM-as-a-Judge Evaluation")
    parser.add_argument("--dataset", default="eval/eval_dataset.json", help="Path to eval dataset JSON")
    parser.add_argument("--api-url", default="http://localhost:8000", help="Chatbot API base URL")
    parser.add_argument("--sample", type=int, default=None, help="Evaluate only N random questions (for quick tests)")
    args = parser.parse_args()
    run_eval(args.dataset, args.api_url, args.sample)
